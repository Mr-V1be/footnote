// Generates TypeScript types of the HTTP API from backend/openapi.json.
//   node scripts/generate-api-types.mjs          write src/shared/api/schema.d.ts
//   node scripts/generate-api-types.mjs --check  fail when the file is stale
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "../backend/openapi.json");
const target = resolve(root, "src/shared/api/schema.d.ts");
const header =
  "// @generated by scripts/generate-api-types.mjs from backend/openapi.json. Do not edit.\n\n";

const document = JSON.parse(await readFile(source, "utf8"));
const ast = await openapiTS(document, { enum: false, exportType: true });
const output = header + astToString(ast);

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== output) {
    console.error("src/shared/api/schema.d.ts is stale: run `pnpm api:generate`");
    process.exit(1);
  }
} else {
  await writeFile(target, output);
  console.log("wrote src/shared/api/schema.d.ts");
}
