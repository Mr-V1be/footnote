// The sign-in pages (a Keycloak theme) share the app's design tokens and icon.
// The app's files are the source; the theme gets generated copies.
//   node scripts/sync-theme-assets.mjs          write the theme copies
//   node scripts/sync-theme-assets.mjs --check  fail when a copy is stale
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const theme = "infra/keycloak/themes/snoska/login/resources";
const ASSETS = [
  {
    source: "frontend/src/shared/tokens/tokens.css",
    target: `${theme}/css/tokens.css`,
    header: (source) =>
      `/* @generated by frontend/scripts/sync-theme-assets.mjs from ${source}. Do not edit. */\n\n`,
  },
  {
    source: "frontend/src/app/icon.svg",
    target: `${theme}/img/icon.svg`,
    header: (source) =>
      `<!-- @generated by frontend/scripts/sync-theme-assets.mjs from ${source}. Do not edit. -->\n`,
  },
];

const check = process.argv.includes("--check");
let stale = false;
for (const asset of ASSETS) {
  const output = asset.header(asset.source) + (await readFile(resolve(root, asset.source), "utf8"));
  const target = resolve(root, asset.target);
  if (check) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== output) {
      console.error(`${asset.target} is stale: run \`pnpm theme:sync\``);
      stale = true;
    }
  } else {
    await writeFile(target, output);
    console.log(`wrote ${asset.target}`);
  }
}
if (stale) process.exit(1);
